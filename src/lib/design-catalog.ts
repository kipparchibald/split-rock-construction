export function formatDelta(n: number): string {
  if (n === 0) return "Included";
  const abs = Math.abs(n);
  const formatted =
    abs >= 100
      ? `$${abs.toLocaleString(undefined, { maximumFractionDigits: 0 })}`
      : `$${abs.toFixed(abs % 1 ? 2 : 0)}`;
  return n > 0 ? `+${formatted}` : `−${formatted}`;
}

