export function partnerCategoryForDesign(cat: DesignCategory): FinishCategory {
  switch (cat) {
    case "paint":
    case "cabinets":
    case "countertops":
    case "backsplash":
    case "tile":
    case "exterior":
    case "roofing":
    case "doors":
      return "general";
    case "flooring":
      return "flooring";
    case "fixtures":
      return "plumbing";
    case "hardware":
      return "hardware";
    case "lighting":
      return "lighting";
    case "appliances":
      return "appliances";
    default:
      return "general";
  }
}

